/** "دقيقة" after a number, by the Arabic plural rules. */
function minutesAr(count: number): string {
  if (count === 1) return 'دقيقة';
  if (count === 2) return 'دقيقتين';
  if (count <= 10) return `${count} دقائق`;
  return `${count} دقيقة`;
}

/** A counted noun by the Arabic plural rules: one, two, three to ten, more. */
function countAr(count: number, one: string, two: string, few: string, many: string): string {
  if (count === 1) return one;
  if (count === 2) return two;
  if (count >= 3 && count <= 10) return `${count} ${few}`;
  return `${count} ${many}`;
}

